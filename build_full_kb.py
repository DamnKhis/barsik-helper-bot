def build_collections():
    print(f"Подключаемся к Qdrant по адресу {QDRANT_URL}...")
    client = QdrantClient(url=QDRANT_URL)
    embedder = TextEmbedding(model_name=EMBEDDING_MODEL)

    # Получаем размерность вектора (384 для multilingual-MiniLM-L12-v2)
    sample_vec = list(embedder.embed(["тест"]))[0]
    dim = len(sample_vec)

    # 1. Пересоздаем коллекцию документации bars_docs
    if client.collection_exists(DOCS_COLLECTION):
        client.delete_collection(DOCS_COLLECTION)
    client.create_collection(
        collection_name=DOCS_COLLECTION,
        vectors_config=VectorParams(size=dim, distance=Distance.COSINE)
    )

    # 2. Создаем коллекцию для Топ-10 частых вопросов (если еще нет)
    if not client.collection_exists(FAQ_COLLECTION):
        client.create_collection(
            collection_name=FAQ_COLLECTION,
            vectors_config=VectorParams(size=dim, distance=Distance.COSINE)
        )

    # Загружаем чанки в bars_docs
    texts = [ clean_text(item["text"]) for item in GOLDEN_CHUNKS ]
    vectors = list(embedder.embed(texts))

    points = []
    for idx, (item, vec) in enumerate(zip(GOLDEN_CHUNKS, vectors)):
        points.append(
            PointStruct(
                id=idx + 1,
                vector=vec.tolist(),
                payload={
                    "chunk_id": f"chunk_{idx+1}",
                    "doc": item["doc_name"],
                    "doc_name": item["doc_name"],
                    "section_path": item["section"],
                    "page": item["page"],
                    "text": clean_text(item["text"]),
                    "image_paths": item["image_paths"]
                }
            )
        )

    client.upsert(collection_name=DOCS_COLLECTION, points=points)
    print(f"✅ Успешно загружено {len(points)} мультимодальных чанков в коллекцию '{DOCS_COLLECTION}'!")
    print(f"✅ Коллекция '{FAQ_COLLECTION}' для сбора Топ-10 частых вопросов готова!")

if __name__ == "__main__":
    build_collections()
