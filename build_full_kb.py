# Регулярка для очистки мусорного колонтитула Word/Confluence (Пункт 1 плана)
HEADER_GARBAGE_RE = re.compile(
    r'Ошибка!\s*Используйте вкладку\s*["«]?Главная["»]?\s*для применения\s*Heading\s*\d+[^\n]*',
    re.IGNORECASE
)

def clean_text(raw_text: str) -> str:
    """Удаляет мусорные колонтитулы и лишние пробелы."""
    text = HEADER_GARBAGE_RE.sub("", raw_text)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()

def extract_valid_images_from_pdf(pdf_path: str, output_dir: str = "static/images") -> list[str]:
    """Извлекает картинки из PDF, отсеивая битые заглушки (красный крестик < 5 КБ) и иконки видео."""
    import fitz  # PyMuPDF
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    saved_images = []
    doc = fitz.open(pdf_path)
    doc_stem = Path(pdf_path).stem

    for page_index in range(len(doc)):
        page = doc[page_index]
        for img_index, img in enumerate(page.get_images(full=True)):
            xref = img[0]
            base_image = doc.extract_image(xref)
            image_bytes = base_image["image"]
            ext = base_image["ext"]
            width, height = base_image.get("width", 0), base_image.get("height", 0)

            # Фильтрация битых картинок-заглушек и мелких иконок .mp4/.webm
            if len(image_bytes) < 5120 or width < 80 or height < 80:
                continue

            img_filename = f"{doc_stem}_p{page_index + 1}_{img_index + 1}.{ext}"
            img_path = os.path.join(output_dir, img_filename)
            with open(img_path, "wb") as f:
                f.write(image_bytes)
            saved_images.append(img_path)
    return saved_images

